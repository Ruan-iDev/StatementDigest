"""FNB (First National Bank) PDF statement parsers — multi-layout island.

Hard rules:
  - Do NOT edit this file to support Capitec, Discovery, or any other bank.
  - Do NOT share line/amount regexes with discovery_pdf.py / capitec_pdf.py.
  - Gold Business English layout is LOCKED (1000+ txs human-verified).
  - Additional FNB layouts are additive variants tried after / alongside Gold Business.

Layouts currently supported:
  1) **Gold Business (English)** — edition-1 locked
     `26 May … 21,845.00Cr 21,845.00Cr`  · bare amount = debit
  2) **Fusion Private Wealth (Afrikaans personal)** — edition-1 sample path
     `25Okt … 42,000.00Kt 41,278.48Kt`  · Kt = krediet (in), bare = debit, Dt = debit bal

When the user picks brand **FNB**, we try each calibrated layout and keep the best
non-empty result (does not replace older layouts).
"""

from __future__ import annotations

import io
import re
from datetime import date
from decimal import Decimal
from typing import Any, Optional

from app.services.money import apply_amount_style, to_decimal
from app.services.parsers.base import ParsedTransaction, _is_balance_row

_MONTHS = {
    "jan": 1,
    "feb": 2,
    "mar": 3,
    "apr": 4,
    "may": 5,
    "mei": 5,
    "jun": 6,
    "jul": 7,
    "aug": 8,
    "sep": 9,
    "oct": 10,
    "okt": 10,
    "nov": 11,
    "dec": 12,
    "des": 12,
}

# ── Layout 1: Gold Business (English) — LOCKED ─────────────────────────────
# 26 May … 21,845.00Cr 21,845.00Cr
# 27 May … 100.00 1,745.00Cr 2.70
_TX_LINE_GOLD = re.compile(
    r"^(?P<day>\d{1,2})\s+"
    r"(?P<mon>Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+"
    r"(?P<desc>.+?)\s+"
    r"(?P<amount>\d{1,3}(?:,\d{3})*\.\d{2}(?:Cr|Dr)?)\s+"
    r"(?P<balance>\d{1,3}(?:,\d{3})*\.\d{2}(?:Cr|Dr)?)"
    r"(?:\s+(?P<charges>\d{1,3}(?:,\d{3})*\.\d{2}))?"
    r"\s*$",
    re.IGNORECASE,
)

# Description is sometimes an image (not text). Then the line is only date + amounts:
#   18 Mar 0.00 32,763.99Cr 80.00     ← amount 0, balance, accrued charges (memo)
#   18 Mar 49.00 32,714.99Cr          ← #Monthly Account Fee
#   18 Mar 121.04 32,593.95Cr         ← #Service Fees
_TX_LINE_GOLD_NODESC = re.compile(
    r"^(?P<day>\d{1,2})\s+"
    r"(?P<mon>Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+"
    r"(?P<amount>\d{1,3}(?:,\d{3})*\.\d{2}(?:Cr|Dr)?)\s+"
    r"(?P<balance>\d{1,3}(?:,\d{3})*\.\d{2}(?:Cr|Dr)?)"
    r"(?:\s+(?P<charges>\d{1,3}(?:,\d{3})*\.\d{2}))?"
    r"\s*$",
    re.IGNORECASE,
)

_GOLD_MONEY_TOKEN = re.compile(r"^\d{1,3}(?:,\d{3})*\.\d{2}(?:Cr|Dr)?$", re.IGNORECASE)

# Gold Business draws fee descriptions as imagemasks, so extracted text is empty.
# Keep the wording printed on the statement — do not substitute the allocation
# ledger name (bank fees/charges). R49.00 is the Gold monthly account fee on
# verified statements; other posted empty-desc debits are service fees.
_GOLD_MONTHLY_ACCOUNT_FEE = Decimal("49.00")
_GOLD_DESC_MONTHLY_ACCOUNT_FEE = "#Monthly Account Fee"
_GOLD_DESC_SERVICE_FEES = "#Service Fees"


def _gold_image_fee_description(amount: Decimal) -> str:
    if abs(amount) == _GOLD_MONTHLY_ACCOUNT_FEE:
        return _GOLD_DESC_MONTHLY_ACCOUNT_FEE
    return _GOLD_DESC_SERVICE_FEES


_PERIOD_RE_GOLD = re.compile(
    r"Statement\s+Period\s*:?\s*"
    r"(\d{1,2})\s+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{4})"
    r"\s*to\s*"
    r"(\d{1,2})\s+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{4})",
    re.IGNORECASE,
)

_STMT_DATE_RE_GOLD = re.compile(
    r"Statement\s+Date\s*:?\s*(\d{1,2})\s+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{4})",
    re.IGNORECASE,
)

_HEADER_DATE_RE = re.compile(
    r"\b(\d{4})[/\-.](\d{1,2})[/\-.](\d{1,2})\b",
)

# ── Layout 2: Fusion Private Wealth (Afrikaans personal) ───────────────────
# PDF text is often tight: 25Okt Smart-Ap… 42,000.00Kt 41,278.48Kt
_TX_LINE_FUSION_AF = re.compile(
    r"^(?P<day>\d{1,2})\s*"
    r"(?P<mon>Jan|Feb|Mar|Apr|Mei|May|Jun|Jul|Aug|Sep|Okt|Oct|Nov|Des|Dec)\s+"
    r"(?P<desc>.+?)\s+"
    r"(?P<amount>\d{1,3}(?:,\d{3})*\.\d{2}(?:Kt|Dt|Cr|Dr)?)\s+"
    r"(?P<balance>\d{1,3}(?:,\d{3})*\.\d{2}(?:Kt|Dt|Cr|Dr)?)"
    r"(?:\s+(?P<charges>\d{1,3}(?:,\d{3})*\.\d{2}))?"
    r"\s*$",
    re.IGNORECASE,
)

# StaatPeriode:24Oktober2024tot23November2024  (spaces optional)
_PERIOD_RE_AF = re.compile(
    r"Staat\s*Periode\s*:?\s*"
    r"(\d{1,2})\s*"
    r"(Jan(?:uarie)?|Feb(?:ruarie)?|Mar(?:t)?|Apr(?:il)?|Mei|May|Jun(?:ie)?|Jul(?:ie)?|"
    r"Aug(?:ustus)?|Sep(?:tember)?|Okt(?:ober)?|Oct(?:ober)?|Nov(?:ember)?|Des(?:ember)?|Dec(?:ember)?)"
    r"\s*(\d{4})"
    r"\s*tot\s*"
    r"(\d{1,2})\s*"
    r"(Jan(?:uarie)?|Feb(?:ruarie)?|Mar(?:t)?|Apr(?:il)?|Mei|May|Jun(?:ie)?|Jul(?:ie)?|"
    r"Aug(?:ustus)?|Sep(?:tember)?|Okt(?:ober)?|Oct(?:ober)?|Nov(?:ember)?|Des(?:ember)?|Dec(?:ember)?)"
    r"\s*(\d{4})",
    re.IGNORECASE,
)

_STMT_DATE_RE_AF = re.compile(
    r"Staat\s*datum\s*:?\s*"
    r"(\d{1,2})\s*"
    r"(Jan(?:uarie)?|Feb(?:ruarie)?|Mar(?:t)?|Apr(?:il)?|Mei|May|Jun(?:ie)?|Jul(?:ie)?|"
    r"Aug(?:ustus)?|Sep(?:tember)?|Okt(?:ober)?|Oct(?:ober)?|Nov(?:ember)?|Des(?:ember)?|Dec(?:ember)?)"
    r"\s*(\d{4})",
    re.IGNORECASE,
)

